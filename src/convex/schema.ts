import { authTables } from "@convex-dev/auth/server";
import { defineSchema, defineTable } from "convex/server";
import { Infer, v } from "convex/values";

export const ROLE_VALUES = [
  "student",
  "faculty",
  "hod",
  "admin",
  "canteen_staff",
  "event_coordinator",
] as const;

export const roleValidator = v.union(
  v.literal("student"),
  v.literal("faculty"),
  v.literal("hod"),
  v.literal("admin"),
  v.literal("canteen_staff"),
  v.literal("event_coordinator"),
);
export type Role = Infer<typeof roleValidator>;

const orderItem = v.object({
  name: v.string(),
  qty: v.number(),
  price: v.number(),
});

const requestHistory = v.object({
  status: v.string(),
  actorName: v.string(),
  actorRole: v.string(),
  remarks: v.optional(v.string()),
  at: v.number(),
});

const planTopic = v.object({
  id: v.string(),
  title: v.string(),
  unit: v.string(),
  minutes: v.number(),
  scheduledDate: v.string(),
  done: v.boolean(),
});

const quizQuestion = v.object({
  id: v.string(),
  question: v.string(),
  options: v.array(v.string()),
  answer: v.number(),
  explanation: v.string(),
});

const chatMessage = v.object({
  id: v.string(),
  role: v.string(),
  content: v.string(),
  grounded: v.optional(v.boolean()),
  citations: v.optional(
    v.array(v.object({ title: v.string(), page: v.number() })),
  ),
});

const schema = defineSchema(
  {
    ...authTables,

    users: defineTable({
      name: v.optional(v.string()),
      image: v.optional(v.string()),
      email: v.optional(v.string()),
      emailVerificationTime: v.optional(v.number()),
      isAnonymous: v.optional(v.boolean()),
      role: v.optional(roleValidator),
      department: v.optional(v.string()),
      departmentId: v.optional(v.string()),
      registerNumber: v.optional(v.string()),
      year: v.optional(v.number()),
      section: v.optional(v.string()),
      phone: v.optional(v.string()),
      bio: v.optional(v.string()),
      status: v.optional(v.union(v.literal("active"), v.literal("disabled"))),
      demo: v.optional(v.boolean()),
    })
      .index("email", ["email"])
      .index("by_role", ["role"]),

    departments: defineTable({
      name: v.string(),
      code: v.string(),
      hod: v.string(),
      facultyCount: v.number(),
      studentCount: v.number(),
    }),
    subjects: defineTable({
      code: v.string(),
      name: v.string(),
      department: v.string(),
      semester: v.number(),
      credits: v.number(),
      faculty: v.string(),
      units: v.array(v.string()),
      color: v.string(),
    }).index("by_department", ["department"]),
    timetableSlots: defineTable({
      day: v.number(),
      start: v.string(),
      end: v.string(),
      subject: v.string(),
      room: v.string(),
      department: v.string(),
      year: v.number(),
      section: v.string(),
      faculty: v.string(),
    }).index("by_scope", ["department", "year", "section"]),
    attendance: defineTable({
      userId: v.id("users"),
      subject: v.string(),
      date: v.string(),
      status: v.union(
        v.literal("present"),
        v.literal("absent"),
        v.literal("od"),
      ),
      source: v.union(v.literal("manual"), v.literal("od")),
    }).index("by_user", ["userId"]),
    marks: defineTable({
      userId: v.id("users"),
      subject: v.string(),
      internal: v.number(),
      maxInternal: v.number(),
      practical: v.number(),
      grade: v.string(),
    }).index("by_user", ["userId"]),
    assignments: defineTable({
      title: v.string(),
      description: v.string(),
      subject: v.string(),
      department: v.string(),
      year: v.number(),
      section: v.string(),
      dueAt: v.number(),
      points: v.number(),
      authorName: v.string(),
      createdAt: v.number(),
    }),
    submissions: defineTable({
      assignmentId: v.id("assignments"),
      userId: v.id("users"),
      userName: v.string(),
      content: v.string(),
      fileName: v.optional(v.string()),
      submittedAt: v.number(),
      status: v.union(
        v.literal("submitted"),
        v.literal("graded"),
        v.literal("returned"),
      ),
      grade: v.optional(v.number()),
      feedback: v.optional(v.string()),
    })
      .index("by_user", ["userId"])
      .index("by_assignment", ["assignmentId"]),
    exams: defineTable({
      subject: v.string(),
      date: v.number(),
      startTime: v.string(),
      room: v.string(),
      type: v.string(),
      department: v.string(),
      year: v.number(),
    }).index("by_department", ["department", "year"]),
    announcements: defineTable({
      title: v.string(),
      body: v.string(),
      audience: v.string(),
      department: v.optional(v.string()),
      authorName: v.string(),
      authorRole: v.string(),
      pinned: v.boolean(),
      createdAt: v.number(),
    }),
    libraryResources: defineTable({
      title: v.string(),
      author: v.string(),
      type: v.string(),
      subject: v.string(),
      department: v.string(),
      unit: v.string(),
      access: v.union(
        v.literal("public"),
        v.literal("department"),
        v.literal("restricted"),
      ),
      description: v.string(),
      content: v.string(),
      pages: v.number(),
      tags: v.array(v.string()),
      year: v.number(),
    }).index("by_department", ["department"]),
    bookmarks: defineTable({
      userId: v.id("users"),
      resourceId: v.id("libraryResources"),
      createdAt: v.number(),
    })
      .index("by_user", ["userId"])
      .index("by_user_resource", ["userId", "resourceId"]),
    requests: defineTable({
      refNo: v.string(),
      type: v.union(v.literal("od"), v.literal("leave")),
      category: v.string(),
      userId: v.id("users"),
      userName: v.string(),
      registerNumber: v.string(),
      department: v.string(),
      year: v.number(),
      section: v.string(),
      title: v.string(),
      organizer: v.optional(v.string()),
      venue: v.optional(v.string()),
      startDate: v.string(),
      endDate: v.string(),
      halfDay: v.boolean(),
      reason: v.string(),
      documentName: v.optional(v.string()),
      status: v.string(),
      currentRole: v.union(
        v.literal("faculty"),
        v.literal("hod"),
        v.literal("admin"),
        v.literal("none"),
      ),
      finalStep: v.boolean(),
      attendanceEffect: v.boolean(),
      history: v.array(requestHistory),
      createdAt: v.number(),
      updatedAt: v.number(),
    })
      .index("by_user", ["userId"])
      .index("by_status", ["status"])
      .index("by_department", ["department", "status"]),
    approvalPolicies: defineTable({
      name: v.string(),
      type: v.union(v.literal("od"), v.literal("leave")),
      category: v.optional(v.string()),
      maxDays: v.optional(v.number()),
      steps: v.array(v.string()),
      finalStepIndex: v.number(),
      attendanceEffect: v.boolean(),
      active: v.boolean(),
    }),
    canteenItems: defineTable({
      name: v.string(),
      price: v.number(),
      category: v.string(),
      description: v.string(),
      available: v.boolean(),
      prepMinutes: v.number(),
      veg: v.boolean(),
      bestseller: v.boolean(),
    }),
    orders: defineTable({
      userId: v.id("users"),
      userName: v.string(),
      items: v.array(orderItem),
      amount: v.number(),
      tokenNo: v.number(),
      status: v.union(
        v.literal("placed"),
        v.literal("preparing"),
        v.literal("ready"),
        v.literal("collected"),
        v.literal("cancelled"),
      ),
      paymentStatus: v.union(v.literal("paid"), v.literal("failed")),
      paymentProvider: v.string(),
      note: v.optional(v.string()),
      idempotencyKey: v.string(),
      createdAt: v.number(),
      updatedAt: v.number(),
    })
      .index("by_user", ["userId"])
      .index("by_status", ["status"]),
    events: defineTable({
      title: v.string(),
      type: v.string(),
      description: v.string(),
      venue: v.string(),
      startAt: v.number(),
      endAt: v.number(),
      fee: v.number(),
      capacity: v.number(),
      coordinatorName: v.string(),
      department: v.string(),
      registrationOpen: v.boolean(),
      tags: v.array(v.string()),
      theme: v.string(),
    }),
    eventRegistrations: defineTable({
      eventId: v.id("events"),
      userId: v.id("users"),
      userName: v.string(),
      status: v.union(v.literal("registered"), v.literal("cancelled")),
      createdAt: v.number(),
    })
      .index("by_user", ["userId"])
      .index("by_event", ["eventId"]),
    lostFound: defineTable({
      type: v.union(v.literal("lost"), v.literal("found")),
      title: v.string(),
      category: v.string(),
      description: v.string(),
      location: v.string(),
      date: v.string(),
      reporterId: v.id("users"),
      reporterName: v.string(),
      contact: v.string(),
      status: v.union(
        v.literal("open"),
        v.literal("claimed"),
        v.literal("resolved"),
      ),
      emoji: v.string(),
      createdAt: v.number(),
    }),
    claims: defineTable({
      itemId: v.id("lostFound"),
      userId: v.id("users"),
      userName: v.string(),
      evidence: v.string(),
      status: v.union(
        v.literal("pending"),
        v.literal("approved"),
        v.literal("rejected"),
      ),
      createdAt: v.number(),
    })
      .index("by_item", ["itemId"])
      .index("by_user", ["userId"]),
    publicProfiles: defineTable({
      userId: v.id("users"),
      displayName: v.string(),
      department: v.string(),
      year: v.number(),
      skills: v.array(v.string()),
      interests: v.array(v.string()),
      lookingFor: v.array(v.string()),
      visibility: v.union(v.literal("public"), v.literal("hidden")),
      bio: v.string(),
    }).index("by_user", ["userId"]),
    connections: defineTable({
      fromId: v.id("users"),
      fromName: v.string(),
      toId: v.id("users"),
      toName: v.string(),
      purpose: v.string(),
      status: v.union(
        v.literal("pending"),
        v.literal("accepted"),
        v.literal("declined"),
      ),
      createdAt: v.number(),
    })
      .index("by_from", ["fromId"])
      .index("by_to", ["toId"]),
    opportunities: defineTable({
      title: v.string(),
      org: v.string(),
      type: v.string(),
      location: v.string(),
      stipend: v.string(),
      link: v.string(),
      verified: v.boolean(),
      description: v.string(),
      tags: v.array(v.string()),
    }),
    communityPosts: defineTable({
      community: v.string(),
      authorId: v.id("users"),
      authorName: v.string(),
      title: v.string(),
      body: v.string(),
      tags: v.array(v.string()),
      createdAt: v.number(),
    }),
    reports: defineTable({
      targetType: v.string(),
      targetId: v.string(),
      targetLabel: v.string(),
      reason: v.string(),
      reporterId: v.id("users"),
      reporterName: v.string(),
      status: v.union(v.literal("open"), v.literal("reviewed")),
      createdAt: v.number(),
    }),
    notifications: defineTable({
      userId: v.id("users"),
      title: v.string(),
      body: v.string(),
      kind: v.string(),
      link: v.string(),
      read: v.boolean(),
      createdAt: v.number(),
    })
      .index("by_user", ["userId"])
      .index("by_user_read", ["userId", "read"]),
    auditLogs: defineTable({
      actorId: v.id("users"),
      actorName: v.string(),
      actorRole: v.string(),
      action: v.string(),
      target: v.string(),
      at: v.number(),
    }),
    tasks: defineTable({
      userId: v.id("users"),
      title: v.string(),
      dueAt: v.optional(v.number()),
      priority: v.union(
        v.literal("low"),
        v.literal("medium"),
        v.literal("high"),
      ),
      done: v.boolean(),
      subject: v.optional(v.string()),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    notes: defineTable({
      userId: v.id("users"),
      title: v.string(),
      body: v.string(),
      subject: v.string(),
      pinned: v.boolean(),
      createdAt: v.number(),
      updatedAt: v.number(),
    }).index("by_user", ["userId"]),
    goals: defineTable({
      userId: v.id("users"),
      title: v.string(),
      target: v.number(),
      progress: v.number(),
      unit: v.string(),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    habits: defineTable({
      userId: v.id("users"),
      name: v.string(),
      emoji: v.string(),
      targetPerWeek: v.number(),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    habitLogs: defineTable({
      userId: v.id("users"),
      habitId: v.id("habits"),
      date: v.string(),
    }).index("by_user", ["userId"]),
    focusSessions: defineTable({
      userId: v.id("users"),
      minutes: v.number(),
      startedAt: v.number(),
      endedAt: v.optional(v.number()),
      subject: v.optional(v.string()),
      status: v.union(
        v.literal("completed"),
        v.literal("interrupted"),
      ),
      kind: v.string(),
    }).index("by_user", ["userId"]),
    workspaceEvents: defineTable({
      userId: v.id("users"),
      title: v.string(),
      date: v.string(),
      time: v.optional(v.string()),
      kind: v.string(),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    studyPlans: defineTable({
      userId: v.id("users"),
      subject: v.string(),
      examDate: v.number(),
      hoursPerDay: v.number(),
      status: v.union(
        v.literal("draft"),
        v.literal("active"),
        v.literal("archived"),
      ),
      topics: v.array(planTopic),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    studyDocs: defineTable({
      userId: v.id("users"),
      title: v.string(),
      subject: v.string(),
      status: v.union(
        v.literal("processing"),
        v.literal("ready"),
        v.literal("failed"),
      ),
      pages: v.number(),
      summary: v.string(),
      keywords: v.array(v.string()),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    quizzes: defineTable({
      userId: v.id("users"),
      subject: v.string(),
      topic: v.string(),
      difficulty: v.string(),
      questions: v.array(quizQuestion),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    quizAttempts: defineTable({
      quizId: v.id("quizzes"),
      userId: v.id("users"),
      subject: v.string(),
      score: v.number(),
      total: v.number(),
      answers: v.array(v.number()),
      createdAt: v.number(),
    }).index("by_user", ["userId"]),
    aiChats: defineTable({
      userId: v.id("users"),
      title: v.string(),
      subject: v.string(),
      mode: v.string(),
      messages: v.array(chatMessage),
      createdAt: v.number(),
      updatedAt: v.number(),
    }).index("by_user", ["userId"]),
    settings: defineTable({
      key: v.string(),
      value: v.string(),
    }).index("by_key", ["key"]),
    counters: defineTable({
      name: v.string(),
      value: v.number(),
    }).index("by_name", ["name"]),
    meta: defineTable({
      key: v.string(),
      value: v.string(),
    }).index("by_key", ["key"]),
  },
  {
    schemaValidation: false,
  },
);

export default schema;
